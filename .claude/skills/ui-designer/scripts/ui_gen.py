#!/usr/bin/env python3
"""ui.json (pse84-ui/1) -> static LVGL 9.5 C code for an app made from template lvgl-ui-app.

Usage:
  ui_gen.py <ui.json> <app-dir> [--dry-run]

Writes (relative to <app-dir>):
  proj_cm55/ui/ui_gen.h, ui_gen.c   GENERATED - rewritten every run, never edit by hand
  proj_cm55/ui/ui_conf.h            GENERATED - fonts the spec uses (included by lv_conf.h)
  proj_cm55/ui/ui_actions.c         DEVELOPER-OWNED - created once; stubs for new "user" events
                                    are appended, nothing is ever removed or rewritten
  shared/ui_ids.h                   GENERATED - indexes, names, IPC_CMD_UI protocol (both cores)
  tests/ui_app.json                 GENERATED - serial_test spec checking the UI on the device
  ui/ui.json                        copy of the spec that produced the code (unless it is the input)

Output lines: GEN: wrote <file> | GEN: STUB added <fn> | GEN: ORPHAN <fn> (in ui_actions.c, no
longer referenced) | GEN: OK | GEN: FAILED (spec errors listed first).
"""
import argparse
import json
