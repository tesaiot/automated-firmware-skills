import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ui_spec  # noqa: E402

HEAD = ("/* GENERATED by ui_gen.py from ui.json ({name}) - do not edit.\n"
        " * Change the UI in the designer / ui.json and regenerate; put your code in ui_actions.c. */\n")
ALIGN_C = {a: "LV_ALIGN_" + a.upper() for a in ui_spec.ALIGNS}
FLOW_C = {"row": "LV_FLEX_FLOW_ROW", "column": "LV_FLEX_FLOW_COLUMN",
          "row_wrap": "LV_FLEX_FLOW_ROW_WRAP", "column_wrap": "LV_FLEX_FLOW_COLUMN_WRAP"}
PLACE_C = {p: "LV_FLEX_ALIGN_" + p.upper() for p in ui_spec.FLEX_PLACES}
LONG_C = {"wrap": "LV_LABEL_LONG_MODE_WRAP", "dot": "LV_LABEL_LONG_MODE_DOTS",
          "scroll": "LV_LABEL_LONG_MODE_SCROLL", "clip": "LV_LABEL_LONG_MODE_CLIP"}
EVENT_C = {"clicked": "LV_EVENT_CLICKED", "pressed": "LV_EVENT_PRESSED", "released": "LV_EVENT_RELEASED",
           "long_pressed": "LV_EVENT_LONG_PRESSED", "value_changed": "LV_EVENT_VALUE_CHANGED"}
CREATE_C = {"container": "lv_obj_create", "label": "lv_label_create", "button": "lv_button_create",
            "slider": "lv_slider_create", "bar": "lv_bar_create", "arc": "lv_arc_create",
            "switch": "lv_switch_create", "checkbox": "lv_checkbox_create",
            "dropdown": "lv_dropdown_create", "spinner": "lv_spinner_create"}
BIND_C = {"label": None, "slider": "lv_slider_bind_value", "bar": "lv_bar_bind_value",
          "arc": "lv_arc_bind_value", "switch": "lv_obj_bind_checked", "checkbox": "lv_obj_bind_checked",
          "button": "lv_obj_bind_checked", "dropdown": "lv_dropdown_bind_value"}
TYPE_LIST = list(ui_spec.TYPES)


def c_str(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 0x20:
            out.append("\\%03o" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def hexcol(c):
    return "lv_color_hex(0x" + c[1:].upper() + ")"


def size_c(v):
    if v == "content":
        return "LV_SIZE_CONTENT"
    if isinstance(v, str) and v.endswith("%"):
        return f"lv_pct({int(v[:-1])})"
    return str(int(v))


def opa_c(pct):
    return f"(lv_opa_t){round(pct * 255 / 100)}"


def style_lines(o, st, wtype):
    L = []
    if "bg" in st:
        L.append(f"lv_obj_set_style_bg_color({o}, {hexcol(st['bg'])}, 0);")
        if "bg_opa" not in st:
            L.append(f"lv_obj_set_style_bg_opa({o}, LV_OPA_COVER, 0);")
    if "bg_opa" in st:
        L.append(f"lv_obj_set_style_bg_opa({o}, {opa_c(st['bg_opa'])}, 0);")
    if "text_color" in st:
        L.append(f"lv_obj_set_style_text_color({o}, {hexcol(st['text_color'])}, 0);")
    if "font" in st:
        L.append(f"lv_obj_set_style_text_font({o}, &lv_font_{st['font']}, 0);")
    if "text_align" in st:
        L.append(f"lv_obj_set_style_text_align({o}, LV_TEXT_ALIGN_{st['text_align'].upper()}, 0);")
    if "radius" in st:
        L.append(f"lv_obj_set_style_radius({o}, {st['radius']}, 0);")
    if "border_width" in st:
        L.append(f"lv_obj_set_style_border_width({o}, {st['border_width']}, 0);")
    if "border_color" in st:
        L.append(f"lv_obj_set_style_border_color({o}, {hexcol(st['border_color'])}, 0);")
    if "pad" in st:
        L.append(f"lv_obj_set_style_pad_all({o}, {st['pad']}, 0);")
    if "gap" in st:
        L.append(f"lv_obj_set_style_pad_row({o}, {st['gap']}, 0);")
        L.append(f"lv_obj_set_style_pad_column({o}, {st['gap']}, 0);")
    if "shadow" in st:
        L.append(f"lv_obj_set_style_shadow_width({o}, {st['shadow']}, 0);")
    if "accent" in st:
        c = hexcol(st["accent"])
        if wtype in ("slider", "bar"):
            L.append(f"lv_obj_set_style_bg_color({o}, {c}, LV_PART_INDICATOR);")
            if wtype == "slider":
                L.append(f"lv_obj_set_style_bg_color({o}, {c}, LV_PART_KNOB);")
        elif wtype in ("arc", "spinner"):
            L.append(f"lv_obj_set_style_arc_color({o}, {c}, LV_PART_INDICATOR);")
            if wtype == "arc":
                L.append(f"lv_obj_set_style_bg_color({o}, {c}, LV_PART_KNOB);")
        elif wtype in ("switch", "checkbox"):
            L.append(f"lv_obj_set_style_bg_color({o}, {c}, (lv_style_selector_t)LV_PART_INDICATOR | (lv_style_selector_t)LV_STATE_CHECKED);")
            if wtype == "checkbox":
                L.append(f"lv_obj_set_style_border_color({o}, {c}, LV_PART_INDICATOR);")
        else:
            L.append(f"lv_obj_set_style_bg_color({o}, {c}, 0);")
    return L


def layout_lines(o, lay):
    L = [f"lv_obj_set_flex_flow({o}, {FLOW_C[lay['flex']]});"]
    main, cross = PLACE_C[lay.get("main", "start")], PLACE_C[lay.get("cross", "start")]
    L.append(f"lv_obj_set_flex_align({o}, {main}, {cross}, {cross});")
    if "gap" in lay:
        L.append(f"lv_obj_set_style_pad_row({o}, {lay['gap']}, 0);")
        L.append(f"lv_obj_set_style_pad_column({o}, {lay['gap']}, 0);")
    return L


def stub_name(wid, ev):
    return f"ui_on_{wid}_{ev}"


class Gen:
    def __init__(self, spec):
        self.s = spec
        self.name = spec["name"]
        self.screens = spec["screens"]
        self.data = spec.get("data") or []
        self.w = list(ui_spec.walk(spec))                   # (widget, parent, screen, ptr)
        self.widx = {w["id"]: i for i, (w, _, _, _) in enumerate(self.w)}
        self.sidx = {s["id"]: i for i, s in enumerate(self.screens)}
        self.didx = {d["id"]: i for i, d in enumerate(self.data)}
        self.stubs = []                                      # (fn, widget id, event)
        for w, _, _, _ in self.w:
            for ev, h in (w.get("on") or {}).items():
                if "user" in ui_spec.actions_of(h):
                    self.stubs.append((stub_name(w["id"], ev), w["id"], ev))

    # ------------------------------------------------------------------ shared/ui_ids.h
    def ids_h(self):
        n_s, n_w, n_d = len(self.screens), len(self.w), len(self.data)
        o = [HEAD.format(name=self.name),
             "/* shared/ui_ids.h - UI indexes, names and the IPC_CMD_UI protocol (CM33 + CM55). */",
             "#ifndef UI_IDS_H", "#define UI_IDS_H", "", "#include <stdint.h>", '#include "ipc_mailbox.h"', "",
             f"#define UI_SPEC_NAME        {c_str(self.name)}",
             f"#define UI_SCREEN_COUNT     ({n_s}U)", f"#define UI_WIDGET_COUNT     ({n_w}U)",
             f"#define UI_DATA_COUNT       ({n_d}U)", ""]
        o += [f"#define UI_S_{s['id'].upper():<18} ({i}U)" for i, s in enumerate(self.screens)]
        o.append("")
        o += [f"#define UI_W_{w['id'].upper():<18} ({i}U)" for i, (w, _, _, _) in enumerate(self.w)]
        if self.w:
            o.append("")
        o += [f"#define UI_D_{d['id'].upper():<18} ({i}U)" for i, d in enumerate(self.data)]
        o += ["",
              "/* IPC_CMD_UI (CM33 -> CM55): arg = UI_ARG(op, index, value), see the ops below */",
              "#define IPC_CMD_UI          (IPC_CMD_APP_BASE + 1UL)",
              "#define UI_ARG(op, idx, val) ((((uint32_t)(op)) << 24) | ((((uint32_t)(idx)) & 0xFFUL) << 16) | \\",
              "                              (((uint32_t)(val)) & 0xFFFFUL))",
              "enum",
              "{",
              "    UI_OP_INFO = 0,     /* idx = UI_INFO_*: counts, events, active screen          */",
              "    UI_OP_XY,           /* idx = widget: (x << 16) | y, int16 each, display pixels  */",
              "    UI_OP_WH,           /* idx = widget: (w << 16) | h                              */",
              "    UI_OP_FLAGS,        /* idx = widget: UI_F_* bits                                */",
              "    UI_OP_VALUE,        /* idx = widget: value / checked / selected (else 0)        */",
              "    UI_OP_GET,          /* idx = data: int32 value                                  */",
              "    UI_OP_SET,          /* idx = data, value = int16 (clamped to min..max)          */",
              "    UI_OP_SCREEN,       /* idx = screen: load it                                    */",
              "    UI_OP_CLICK         /* idx = widget: send LV_EVENT_CLICKED (no toggle, no anim) */",
              "};",
              "enum { UI_INFO_SCREENS = 0, UI_INFO_WIDGETS, UI_INFO_DATA, UI_INFO_EVENTS, UI_INFO_LAST, UI_INFO_ACTIVE };",
              "#define UI_F_VISIBLE        (1UL << 0)   /* not hidden (itself and its parents)  */",
              "#define UI_F_ACTIVE         (1UL << 1)   /* on the loaded screen                  */",
              "#define UI_F_INSIDE         (1UL << 2)   /* box inside the 800x480 display        */",
              "/* UI_INFO_LAST = (widget << 8) | event, event index into ui_event_names */",
              "enum { " + ", ".join(f"UI_EV_{e.upper()}" for e in ui_spec.EVENTS) + " };",
              "enum { " + ", ".join(f"UI_T_{t.upper()}" for t in TYPE_LIST) + " };",
              "",
              "#ifdef UI_IDS_NAMES      /* define before including, in one .c file only */",
              "static const char *const ui_screen_names[UI_SCREEN_COUNT + 1U] = { "
              + "".join(f"{c_str(s['id'])}, " for s in self.screens) + "0 };",
              "static const char *const ui_widget_names[UI_WIDGET_COUNT + 1U] = { "
              + "".join(f"{c_str(w['id'])}, " for w, _, _, _ in self.w) + "0 };",
              "static const uint8_t     ui_widget_types[UI_WIDGET_COUNT + 1U] = { "
              + "".join(f"UI_T_{w['type'].upper()}, " for w, _, _, _ in self.w) + "0 };",
              "static const uint8_t     ui_widget_screen[UI_WIDGET_COUNT + 1U] = { "
              + "".join(f"{self.sidx[scr['id']]}, " for _, _, scr, _ in self.w) + "0 };",
              "static const char *const ui_data_names[UI_DATA_COUNT + 1U] = { "
              + "".join(f"{c_str(d['id'])}, " for d in self.data) + "0 };",
              "static const char *const ui_event_names[] = { "
              + ", ".join(c_str(e) for e in ui_spec.EVENTS) + " };",
              "static const char *const ui_type_names[] = { "
              + ", ".join(c_str(t) for t in TYPE_LIST) + " };",
              "#endif", "", "#endif /* UI_IDS_H */", ""]
        return "\n".join(o)

    # ------------------------------------------------------------------ ui_conf.h
    def conf_h(self):
        o = [HEAD.format(name=self.name), "/* Fonts used by the UI, enabled on top of lv_conf.h (which includes this file). */",
             "#ifndef UI_CONF_H", "#define UI_CONF_H", ""]
        for f in ui_spec.fonts_used(self.s):
            m = f"LV_FONT_MONTSERRAT_{ui_spec.font_px(f)}"
            o += [f"#undef  {m}", f"#define {m} 1"]
        o += ["", "#endif /* UI_CONF_H */", ""]
        return "\n".join(o)

    # ------------------------------------------------------------------ ui_gen.h
    def gen_h(self):
        o = [HEAD.format(name=self.name),
             "/* ui_gen.h - the designed UI: every screen and widget as ui.<id>, every data item as",
             " * an LVGL subject ui_data_<id> (widgets bound to it follow it both ways). */",
             "#ifndef UI_GEN_H", "#define UI_GEN_H", "", "#include <stdint.h>", '#include "lvgl.h"',
             '#include "ui_ids.h"', "", "typedef struct", "{"]
        o += [f"    lv_obj_t *{s['id']};{'':<10}/* screen */" for s in self.screens]
        o += [f"    lv_obj_t *{w['id']};{'':<10}/* {w['type']} */" for w, _, _, _ in self.w]
        o += ["} ui_t;", "", "extern ui_t ui;", ""]
        for d in self.data:
            src = f"   /* source: {d['source']} */" if d.get("source") else ""
            o.append(f"extern lv_subject_t ui_data_{d['id']};{src}")
        o += ["",
              "void     ui_gen_create(void);                       /* theme, data, every screen; loads the first */",
              "void     ui_data_set(uint32_t idx, int32_t value);  /* UI_D_*; clamped to min..max */",
              "int32_t  ui_data_get(uint32_t idx);",
              "uint32_t ui_gen_ipc(uint32_t arg, uint32_t *result); /* IPC_CMD_UI server, call from the main loop */",
              "", "/* events handled in ui_actions.c (developer code) */"]
        o += [f"void {fn}(lv_event_t *e);" for fn, _, _ in self.stubs] or ["/* (none) */"]
        o += ["", "#endif /* UI_GEN_H */", ""]
        return "\n".join(o)

    # ------------------------------------------------------------------ ui_gen.c
    def action_lines(self, a):
        if a == "user":
            return []
        if "goto" in a:
            return [f"lv_screen_load(ui.{a['goto']});"]
        if "set" in a:
            return [f"ui_data_set(UI_D_{a['set'].upper()}, {a['value']});"]
        if "inc" in a:
            d = a["inc"].upper()
            return [f"ui_data_set(UI_D_{d}, ui_data_get(UI_D_{d}) + ({a.get('by', 1)}));"]
        if "toggle" in a:
            d = a["toggle"].upper()
            return [f"ui_data_set(UI_D_{d}, (0 != ui_data_get(UI_D_{d})) ? 0 : 1);"]
        return []

    def widget_lines(self, w, parent_var, parent_has_layout):
        t, wid = w["type"], w["id"]
        o = f"ui.{wid}"
        L = [f"{o} = {CREATE_C[t]}({parent_var});"]
        if "w" in w and "h" in w:
            L.append(f"lv_obj_set_size({o}, {size_c(w['w'])}, {size_c(w['h'])});")
        elif "w" in w:
            L.append(f"lv_obj_set_width({o}, {size_c(w['w'])});")
        elif "h" in w:
            L.append(f"lv_obj_set_height({o}, {size_c(w['h'])});")
        if not parent_has_layout and ("align" in w or "x" in w or "y" in w):
            L.append(f"lv_obj_align({o}, {ALIGN_C[w.get('align', 'top_left')]}, {w.get('x', 0)}, {w.get('y', 0)});")
        if "grow" in w:
            L.append(f"lv_obj_set_flex_grow({o}, {w['grow']});")
        if t == "label":
            if "long_mode" in w:
                L.append(f"lv_label_set_long_mode({o}, {LONG_C[w['long_mode']]});")
            if "bind" not in w:
                L.append(f"lv_label_set_text({o}, {c_str(w.get('text', ''))});")
        elif t == "button":
            if w.get("checkable"):
                L.append(f"lv_obj_add_flag({o}, LV_OBJ_FLAG_CHECKABLE);")
            if "text" in w:
                L += ["{", f"    lv_obj_t *txt = lv_label_create({o});",
                      f"    lv_label_set_text(txt, {c_str(w['text'])});",
                      "    lv_obj_center(txt);", "}"]
        elif t in ("slider", "bar", "arc"):
            lo, hi = w.get("min", 0), w.get("max", 100)
            L.append(f"lv_{t}_set_range({o}, {lo}, {hi});")
            if "value" in w:
                L.append(f"lv_{t}_set_value({o}, {w['value']}" + (", LV_ANIM_OFF);" if t != "arc" else ");"))
        elif t == "checkbox":
            L.append(f"lv_checkbox_set_text({o}, {c_str(w.get('text', ''))});")
        elif t == "dropdown":
            L.append(f"lv_dropdown_set_options({o}, {c_str(chr(10).join(w['options']))});")
            if "selected" in w:
                L.append(f"lv_dropdown_set_selected({o}, {w['selected']}U);")
        if t in ("switch", "checkbox", "button") and w.get("checked"):
            L.append(f"lv_obj_add_state({o}, LV_STATE_CHECKED);")
        if "bind" in w:
            subj = f"&ui_data_{w['bind']}"
            if t == "label":
                L.append(f"(void)lv_label_bind_text({o}, {subj}, {c_str(w.get('fmt', '%d'))});")
            else:
                L.append(f"(void){BIND_C[t]}({o}, {subj});")
        if w.get("layout"):
            L += layout_lines(o, w["layout"])
        if w.get("style"):
            L += style_lines(o, w["style"], t)
        if w.get("hidden"):
            L.append(f"lv_obj_add_flag({o}, LV_OBJ_FLAG_HIDDEN);")
        for ev in (w.get("on") or {}):
            L.append(f"lv_obj_add_event_cb({o}, on_{wid}_{ev}, {EVENT_C[ev]}, NULL);")
        return L

    def gen_c(self):
        P = ["#if UI_WIDGET_COUNT > 0U"]
        o = [HEAD.format(name=self.name),
             "/* ui_gen.c - builds the UI designed in ui.json with LVGL 9.5 (lvgl-ui component, CM55).",
             " * Runs in the LVGL context only (main loop); ui_gen_ipc() is called from that loop too. */",
             '#include "ui_gen.h"', "", "ui_t ui;"]
        for d in self.data:
            o.append(f"lv_subject_t ui_data_{d['id']};")
        o += ["", "static volatile uint32_t ev_count;", "static volatile uint32_t ev_last;", ""]
        # tables
        o.append("static lv_obj_t **const screens[UI_SCREEN_COUNT] = { "
                 + ", ".join(f"&ui.{s['id']}" for s in self.screens) + " };")
        if self.w:
            o += P + ["static lv_obj_t **const widgets[UI_WIDGET_COUNT] = {"]
            o += [f"    &ui.{w['id']}," for w, _, _, _ in self.w]
            o += ["};", "static const uint8_t wtypes[UI_WIDGET_COUNT] = { "
                  + ", ".join(f"UI_T_{w['type'].upper()}" for w, _, _, _ in self.w) + " };", "#endif"]
        if self.data:
            o += ["#if UI_DATA_COUNT > 0U",
                  "static lv_subject_t *const subjects[UI_DATA_COUNT] = { "
                  + ", ".join(f"&ui_data_{d['id']}" for d in self.data) + " };",
                  "static const int32_t data_min[UI_DATA_COUNT] = { "
                  + ", ".join(str(d['min']) if 'min' in d else "INT32_MIN" for d in self.data) + " };",
                  "static const int32_t data_max[UI_DATA_COUNT] = { "
                  + ", ".join(str(d['max']) if 'max' in d else "INT32_MAX" for d in self.data) + " };",
                  "#endif"]
        if any(w.get("on") for w, _, _, _ in self.w):
            o += ["", "static void note(uint32_t widget, uint32_t event)", "{",
                  "    ev_count++;", "    ev_last = (widget << 8) | event;", "}", ""]
        # data api
        o += ["void ui_data_set(uint32_t idx, int32_t value)", "{"]
        if self.data:
            o += ["#if UI_DATA_COUNT > 0U", "    if (idx < UI_DATA_COUNT)", "    {",
                  "        if (value < data_min[idx]) { value = data_min[idx]; }",
                  "        if (value > data_max[idx]) { value = data_max[idx]; }",
                  "        lv_subject_set_int(subjects[idx], value);", "    }", "#endif"]
        else:
            o += ["    (void)idx;", "    (void)value;"]
        o += ["}", "", "int32_t ui_data_get(uint32_t idx)", "{"]
        if self.data:
            o += ["#if UI_DATA_COUNT > 0U", "    return (idx < UI_DATA_COUNT) ? lv_subject_get_int(subjects[idx]) : 0;", "#endif"]
        else:
            o += ["    (void)idx;", "    return 0;"]
        o += ["}", ""]
        # event handlers
        for w, _, _, _ in self.w:
            for ev, h in (w.get("on") or {}).items():
                o += [f"static void on_{w['id']}_{ev}(lv_event_t *e)", "{"]
                o.append(f"    note(UI_W_{w['id'].upper()}, UI_EV_{ev.upper()});")
                for a in ui_spec.actions_of(h):
                    if a == "user":
                        o.append(f"    {stub_name(w['id'], ev)}(e);")
                    else:
                        o += ["    " + line for line in self.action_lines(a)]
                if "user" not in ui_spec.actions_of(h):
                    o.append("    LV_UNUSED(e);")
                o += ["}", ""]
        # screens
        for s in self.screens:
            o += [f"static void create_{s['id']}(void)", "{",
                  f"    ui.{s['id']} = lv_obj_create(NULL);"]
            if s.get("layout"):
                o += ["    " + line for line in layout_lines(f"ui.{s['id']}", s["layout"])]
            if s.get("style"):
                o += ["    " + line for line in style_lines(f"ui.{s['id']}", s["style"], "screen")]

            def rec(node, var, has_layout, depth):
                for ch in node.get("children") or []:
                    o.append("")
                    o.append(f"    /* {ch['id']} ({ch['type']}) */")
                    o.extend("    " + line for line in self.widget_lines(ch, var, has_layout))
                    rec(ch, f"ui.{ch['id']}", bool(ch.get("layout")), depth + 1)
            rec(s, f"ui.{s['id']}", bool(s.get("layout")), 1)
            o += ["}", ""]
        th = self.s.get("theme") or {}
        o += ["void ui_gen_create(void)", "{",
              "    lv_display_t *disp = lv_display_get_default();",
              "    lv_theme_t *th = lv_theme_default_init(disp, "
              f"{hexcol(th.get('primary', '#2196F3'))}, {hexcol(th.get('secondary', '#F44336'))}, "
              f"{'true' if th.get('dark') else 'false'}, &lv_font_{th.get('font', 'montserrat_14')});",
              "    lv_display_set_theme(disp, th);", ""]
        for d in self.data:
            o.append(f"    lv_subject_init_int(&ui_data_{d['id']}, {d.get('init', 0)});")
        if self.data:
            o.append("")
        o += [f"    create_{s['id']}();" for s in self.screens]
