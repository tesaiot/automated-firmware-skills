    # ------------------------------------------------------------------ ui_actions.c
    def actions_c(self, existing):
        have = set(re.findall(r"^\s*void\s+(ui_on_\w+)\s*\(", existing or "", re.M))
        want = {fn for fn, _, _ in self.stubs}
        added = [s for s in self.stubs if s[0] not in have]
        orphans = sorted(have - want)
        if existing is None:
            text = ["/* ui_actions.c - YOUR code for the UI events marked \"user\" in ui.json.",
                    " * ui_gen.py creates this file once and later only APPENDS stubs for new events;",
                    " * it never changes or removes what is here. Runs in the LVGL context (CM55 main",
                    " * loop): use ui.<id>, ui_data_set()/ui_data_get(), any lv_* call. */",
                    '#include "ui_gen.h"', ""]
            body = "\n".join(text)
        else:
            body = existing.rstrip("\n") + "\n"
        for fn, wid, ev in added:
            body += (f"\n/* {wid}: {ev} */\nvoid {fn}(lv_event_t *e)\n{{\n"
                     f"    LV_UNUSED(e);\n    /* TODO */\n}}\n")
        return body, [a[0] for a in added], orphans

