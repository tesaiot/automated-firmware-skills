/*******************************************************************************
* File Name : radar_bgt60.h                   component: radar-bgt60 (planned)
*
* Layer 1 - BSP. Infineon XENSIV BGT60TR13C 60 GHz FMCW radar (U5) of the PSOC
*   Edge E84 AI Kit: 1 TX / 3 RX antennas in package, 80 MHz clock from U24.
*   SPI SCB3 (CYBSP_SPI_CONTROLLER): MISO P21.4, MOSI P21.5, CLK P21.6,
*   CS P21.7 (CYBSP_RSPI_*), IRQ P20.3 (CYBSP_RADAR_INT), reset P20.7
*   (CYBSP_RXRES_L, active low), 1.8 V I/O.
* Backend: Infineon sensor-xensiv-bgt60trxx v2, PSOC Edge iface
*   (xensiv_bgt60trxx_edge.h: xensiv_bgt60trxx_mtb_init(obj, regs, len) +
*   xensiv_bgt60trxx_mtb_interrupt_init(obj, fifo_limit), PDL SPI).
* Register set: generated by Radar Fusion GUI / the deepcraft-deploy-radar
*   example as a uint32_t array (radar_settings.h) - passed in, not hard-coded.
* Bring-up runs on CM33_NS (console tests); ML pipelines may move it to CM55
*   later (same API, files under proj_cm55).
*******************************************************************************/
#ifndef RADAR_BGT60_H
#define RADAR_BGT60_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include "bsp_status.h"

typedef struct
{
    const uint32_t *regs;        /* register list from radar_settings.h        */
    size_t          num_regs;
    uint32_t        samples_per_frame; /* chirps * samples * rx antennas       */
    uint16_t        fifo_limit;  /* IRQ when FIFO holds this many samples     */
} radar_config_t;

/* Hard reset (RXRES_L), SPI init, chip check, load registers. */
bsp_status_t radar_init(const radar_config_t *cfg);
void         radar_deinit(void);
bsp_status_t radar_chip_id(uint32_t *id);   /* XENSIV_BGT60TRXX_DEVICE_*     */

bsp_status_t radar_start(void);             /* start frame generation         */
bsp_status_t radar_stop(void);

/* Frame-ready on P20.3. cb runs in IRQ context: set a flag / give a semaphore
 * only. NULL disables. radar_frame_ready() polls the latched flag. */
bsp_status_t radar_set_frame_cb(void (*cb)(void *arg), void *arg);
bool         radar_frame_ready(void);

/* Copy one frame (12-bit samples in uint16_t) out of the FIFO.
 * BSP_ERR_OVERFLOW if the FIFO overflowed (restart with radar_start). */
bsp_status_t radar_read_frame(uint16_t *buf, uint32_t num_samples);

/* SPI self-test: data test mode, compares the LFSR test words. */
bsp_status_t radar_selftest(void);

uint32_t     radar_last_rslt(void);

#endif /* RADAR_BGT60_H */
